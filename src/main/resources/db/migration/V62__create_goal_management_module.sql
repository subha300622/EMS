CREATE INDEX IF NOT EXISTS idx_goals_org_id ON goals(organization_id);
CREATE INDEX IF NOT EXISTS idx_goals_org_owner ON goals(organization_id, owner_id);
CREATE INDEX IF NOT EXISTS idx_goals_org_status ON goals(organization_id, status);
CREATE INDEX IF NOT EXISTS idx_goals_org_parent ON goals(organization_id, parent_goal_id);
CREATE INDEX IF NOT EXISTS idx_goals_org_project ON goals(organization_id, project_id);

-- 2. Goal Assignments
CREATE TABLE IF NOT EXISTS goal_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    assigned_to_employee_id BIGINT,
    department_id BIGINT,
    team_id BIGINT,
    branch_id BIGINT,
    role_id BIGINT,
    assignment_level VARCHAR(50) NOT NULL,
    assignment_type VARCHAR(50) NOT NULL,
    assigned_by BIGINT,
    assigned_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_goal_assign_org_goal ON goal_assignments(organization_id, goal_id);
CREATE INDEX IF NOT EXISTS idx_goal_assign_org_emp ON goal_assignments(organization_id, assigned_to_employee_id);
CREATE INDEX IF NOT EXISTS idx_goal_assign_org_dept ON goal_assignments(organization_id, department_id);
CREATE INDEX IF NOT EXISTS idx_goal_assign_org_team ON goal_assignments(organization_id, team_id);

-- 3. Goal Assignment History
CREATE TABLE IF NOT EXISTS goal_assignment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL,
    assignment_id BIGINT,
    assigned_to BIGINT,
    assigned_by BIGINT,
    previous_owner_id BIGINT,
    department_id BIGINT,
    team_id BIGINT,
    role_id BIGINT,
    assignment_level VARCHAR(50),
    assignment_type VARCHAR(50),
    assignment_reason TEXT,
    assigned_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    unassigned_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_goal_assign_hist_org_goal ON goal_assignment_history(organization_id, goal_id);

-- 4. Append-Only Goal Progress History
CREATE TABLE IF NOT EXISTS goal_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    percentage INT NOT NULL,
    target_achieved DOUBLE PRECISION,
    milestone_completed INT,
    tasks_completed INT,
    update_comment TEXT,
    evidence_document VARCHAR(255),
    updated_by BIGINT,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_progress_org_goal ON goal_progress(organization_id, goal_id);

-- 5. Goal Milestones
CREATE TABLE IF NOT EXISTS goal_milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    target_date DATE,
    weightage INT DEFAULT 1,
    status VARCHAR(50) DEFAULT 'PENDING',
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    completed_by BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_milestone_org_goal ON goal_milestones(organization_id, goal_id);

-- 6. Goal Effort Entries
CREATE TABLE IF NOT EXISTS goal_effort_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    employee_id BIGINT NOT NULL,
    work_date DATE NOT NULL,
    hours DOUBLE PRECISION NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_effort_org_goal ON goal_effort_entries(organization_id, goal_id);
CREATE INDEX IF NOT EXISTS idx_goal_effort_org_emp ON goal_effort_entries(organization_id, employee_id);

-- 7. Goal Comments
CREATE TABLE IF NOT EXISTS goal_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL DEFAULT 1,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    parent_comment_id BIGINT,
    comment TEXT NOT NULL,
    created_by BIGINT NOT NULL DEFAULT 1,
    is_edited BOOLEAN DEFAULT FALSE,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

