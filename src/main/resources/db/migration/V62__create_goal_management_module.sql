CREATE TABLE IF NOT EXISTS goal_assignment_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    rule_name VARCHAR(100) NOT NULL,
    target_level VARCHAR(50) NOT NULL,
    auto_reassign_on_transfer BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS goal_notification_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    email_enabled BOOLEAN DEFAULT TRUE,
    in_app_enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_goal_notif_org_event UNIQUE (organization_id, event_type)
);

CREATE TABLE IF NOT EXISTS goal_number_formats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL UNIQUE,
    prefix VARCHAR(20) DEFAULT 'GOAL',
    sequence_length INT DEFAULT 5,
    current_sequence BIGINT DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS goal_visibility_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    visibility_code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_goal_visibility_org_code UNIQUE (organization_id, visibility_code)
);

-- 11. Goal Approval Policies Table
CREATE TABLE IF NOT EXISTS goal_approval_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    policy_name VARCHAR(150) NOT NULL,
    module VARCHAR(50) DEFAULT 'GOAL',
    action VARCHAR(50) NOT NULL,
    approval_required BOOLEAN DEFAULT TRUE,
    approval_type VARCHAR(50) DEFAULT 'MANAGER',
    priority VARCHAR(50),
    goal_type VARCHAR(50),
    weightage_threshold INT DEFAULT 0,
    estimated_hours_threshold DOUBLE PRECISION DEFAULT 0.0,
    department_id BIGINT,
    approver_role VARCHAR(50),
    approval_levels INT DEFAULT 1,
    auto_approval BOOLEAN DEFAULT FALSE,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_approval_policies_org ON goal_approval_policies(organization_id, is_active);
