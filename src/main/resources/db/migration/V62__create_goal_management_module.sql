ALTER TABLE goal_comments ADD COLUMN IF NOT EXISTS parent_comment_id BIGINT;
ALTER TABLE goal_comments ADD COLUMN IF NOT EXISTS created_by BIGINT DEFAULT 1;
ALTER TABLE goal_comments ADD COLUMN IF NOT EXISTS is_edited BOOLEAN DEFAULT FALSE;
ALTER TABLE goal_comments ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN DEFAULT FALSE;
