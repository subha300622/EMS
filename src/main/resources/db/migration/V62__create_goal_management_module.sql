-- Goal Management Module Schema Definition with Multi-Tenant Indexes

-- 1. Main Goals Table (Supports upgrade from legacy V1 goals table)
CREATE TABLE IF NOT EXISTS goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL DEFAULT 1,
    goal_number VARCHAR(50),
    goal_name VARCHAR(255),
    description TEXT,
    category VARCHAR(100),
    type VARCHAR(100),
    priority VARCHAR(50),
    weightage INT DEFAULT 1,
    progress INT DEFAULT 0,
    start_date DATE,
    end_date DATE,
    target_value DOUBLE PRECISION,
    current_value DOUBLE PRECISION DEFAULT 0.0,
    unit_of_measurement VARCHAR(50),
    owner_id BIGINT,
    estimated_hours DOUBLE PRECISION DEFAULT 0.0,
    actual_hours DOUBLE PRECISION DEFAULT 0.0,
    status VARCHAR(50) DEFAULT 'DRAFT',
    visibility VARCHAR(50) DEFAULT 'PUBLIC',
    parent_goal_id BIGINT,
    project_id BIGINT,
    created_by BIGINT,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    version BIGINT DEFAULT 0
);

