UPDATE goal_comments SET organization_id = 1 WHERE organization_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_goal_comment_org_goal ON goal_comments(organization_id, goal_id);

-- 8. Goal Attachments
CREATE TABLE IF NOT EXISTS goal_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    progress_id BIGINT,
    comment_id BIGINT,
    milestone_id BIGINT,
    file_reference VARCHAR(500) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(100),
    uploaded_by BIGINT NOT NULL,
    uploaded_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_attach_org_goal ON goal_attachments(organization_id, goal_id);

-- 9. Immutable Goal Activities Timeline Audit Log
CREATE TABLE IF NOT EXISTS goal_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
    actor_employee_id BIGINT,
    actor_name VARCHAR(255),
    actor_role VARCHAR(100),
    action VARCHAR(100) NOT NULL,
    description TEXT,
    metadata TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_activity_org_goal ON goal_activities(organization_id, goal_id);

-- 10. Normalized Configuration Tables
CREATE TABLE IF NOT EXISTS goal_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL UNIQUE,
    min_weightage INT DEFAULT 1,
    max_weightage INT DEFAULT 100,
    allow_milestone_progress_calc BOOLEAN DEFAULT TRUE,
    allow_auto_reassignment BOOLEAN DEFAULT TRUE,
    require_approval_for_create BOOLEAN DEFAULT FALSE,
    require_approval_for_complete BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_goal_configs_org ON goal_configs(organization_id);

CREATE TABLE IF NOT EXISTS goal_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_goal_category_org_code UNIQUE (organization_id, code)
);

CREATE TABLE IF NOT EXISTS goal_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_goal_type_org_code UNIQUE (organization_id, code)
