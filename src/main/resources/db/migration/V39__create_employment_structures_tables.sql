CREATE TABLE IF NOT EXISTS public.designations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designation VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS public.job_levels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designation_id BIGINT NOT NULL REFERENCES public.designations(id) ON DELETE CASCADE,
    job_level VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS public.employment_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_level_id BIGINT NOT NULL REFERENCES public.job_levels(id) ON DELETE CASCADE,
    employment_type VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
);
